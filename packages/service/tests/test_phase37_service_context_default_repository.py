from crosswalk_service import ServiceContext

from crosswalk_mapping import MappingCandidate, MappingStatus


def candidate() -> MappingCandidate:
    return MappingCandidate(
        external_path="$.id",
        canonical_path=None,
        score=0,
        status=MappingStatus.UNRESOLVED,
        evidence=None,
    )


def test_context_default_repository() -> None:
    context = ServiceContext()
    assert context.reviews.repository is not None
